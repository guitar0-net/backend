"""Serializer for the report submission payload."""

import uuid
from typing import Any

from rest_framework import serializers

from apps.reports.constants import (
    REASONS_REQUIRING_MESSAGE,
    ClientPlatform,
    ReportReason,
    ReportTargetType,
)


class ReportCreateRequestSerializer(serializers.Serializer[None]):
    """Validates a report sent by a client.

    `id` is generated by the client and makes resubmission idempotent.
    `target_id` is required for content targets and must be empty for `app`.
    It is stored in canonical form (lowercase hyphenated UUID, or a plain
    integer), since `uuid.UUID` and `int` accept many spellings of one id
    and the stored string is what staff search and group reports by.
    `reason` may be any known code, not only those offered for `target_type`.
    It is a plain string in the schema rather than an enum, so a client
    generated before a reason was added can still send a code it learned
    from `GET reports/reasons/`.
    """

    id = serializers.UUIDField()
    target_type = serializers.ChoiceField(choices=ReportTargetType.choices)
    target_id = serializers.CharField(
        max_length=64, required=False, allow_blank=True, default=""
    )
    content_version = serializers.DateTimeField(
        required=False,
        allow_null=True,
        default=None,
        help_text="`version` from the last sync payload the client applied.",
    )
    reason = serializers.CharField(
        max_length=30, help_text="A reason code from GET reports/reasons/."
    )
    message = serializers.CharField(
        max_length=2000, required=False, allow_blank=True, default=""
    )
    contact_email = serializers.EmailField(required=False, allow_blank=True, default="")
    device_id = serializers.CharField(max_length=64)
    platform = serializers.ChoiceField(choices=ClientPlatform.choices)
    app_version = serializers.CharField(max_length=32)
    os_version = serializers.CharField(
        max_length=32, required=False, allow_blank=True, default=""
    )
    locale = serializers.CharField(
        max_length=16, required=False, allow_blank=True, default=""
    )
    screen = serializers.CharField(
        max_length=64, required=False, allow_blank=True, default=""
    )

    def validate_reason(self, value: str) -> str:  # noqa: PLR6301
        """Reject a reason code the server does not know."""
        if value not in ReportReason.values:
            raise serializers.ValidationError(f"Unknown reason {value!r}.")
        return value

    def validate(self, attrs: dict[str, Any]) -> dict[str, Any]:  # noqa: PLR6301
        """Check the fields that only make sense together."""
        target_type = attrs["target_type"]
        if target_type == ReportTargetType.APP and attrs["target_id"]:
            raise serializers.ValidationError({
                "target_id": "Must be empty when target_type is app."
            })
        if target_type != ReportTargetType.APP and not attrs["target_id"]:
            raise serializers.ValidationError({
                "target_id": f"Required when target_type is {target_type}."
            })
        if target_type in {ReportTargetType.CHORD, ReportTargetType.SCHEME}:
            if not attrs["target_id"].isdecimal():
                raise serializers.ValidationError({
                    "target_id": f"Must be an integer for target_type {target_type}."
                })
            attrs["target_id"] = str(int(attrs["target_id"]))
        elif target_type != ReportTargetType.APP:
            try:
                attrs["target_id"] = str(uuid.UUID(attrs["target_id"]))
            except ValueError:
                raise serializers.ValidationError({
                    "target_id": f"Must be a UUID for target_type {target_type}."
                }) from None
        if attrs["reason"] in REASONS_REQUIRING_MESSAGE and not attrs["message"]:
            raise serializers.ValidationError({
                "message": f"Required when reason is {attrs['reason']}."
            })
        return attrs
