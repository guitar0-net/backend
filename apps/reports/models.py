"""Models for the reports app."""

import uuid
from typing import ClassVar

from django.conf import settings
from django.db import models

from apps.reports.constants import (
    ClientPlatform,
    ReportReason,
    ReportStatus,
    ReportTargetType,
)


class Report(models.Model):
    """A user's report about a content item or the app itself.

    The primary key is generated by the client: the mobile app is
    offline-first and queues reports until it is online, so a retried
    submission must be recognisable as the same report rather than a
    duplicate.

    The target is stored as `target_type` + `target_id` (the public id the
    client knows: a UUID for songs, lessons and courses, an integer for
    chords and schemes) instead of a foreign key, because some targets are
    not rows at all (`app`). `target_title` and `target_updated_at` are
    captured at submission time, so staff can tell whether the content has
    been edited since — or deleted — without the report losing its meaning.

    `user` is set when the caller is signed in; `device_id` is always set,
    since sign-in is optional and it is the only stable reporter identity.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    target_type = models.CharField(
        "Тип объекта", max_length=20, choices=ReportTargetType.choices
    )
    target_id = models.CharField(
        "ID объекта",
        max_length=64,
        blank=True,
        default="",
        help_text="UUID песни, урока или курса; число для аккорда или схемы",
    )
    target_title = models.CharField(
        "Название объекта на момент отчёта", max_length=255, blank=True, default=""
    )
    target_updated_at = models.DateTimeField(
        "Объект обновлён (на момент отчёта)", null=True, blank=True
    )
    reason = models.CharField("Причина", max_length=30, choices=ReportReason.choices)
    message = models.TextField("Сообщение", blank=True, default="")
    contact_email = models.EmailField(
        "Email для ответа",
        blank=True,
        default="",
        help_text="Указан пользователем и не подтверждён",
    )
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        verbose_name="Пользователь",
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="reports",
    )
    device_id = models.CharField("ID устройства", max_length=64)
    platform = models.CharField(
        "Платформа", max_length=10, choices=ClientPlatform.choices
    )
    app_version = models.CharField("Версия приложения", max_length=32)
    os_version = models.CharField("Версия ОС", max_length=32, blank=True, default="")
    locale = models.CharField("Локаль", max_length=16, blank=True, default="")
    screen = models.CharField("Экран", max_length=64, blank=True, default="")
    status = models.CharField(
        "Статус",
        max_length=20,
        choices=ReportStatus.choices,
        default=ReportStatus.NEW,
    )
    staff_note = models.TextField("Заметка", blank=True, default="")
    created_at = models.DateTimeField("Создан", auto_now_add=True)
    updated_at = models.DateTimeField("Обновлён", auto_now=True)

    class Meta:
        verbose_name = "Отчёт пользователя"
        verbose_name_plural = "Отчёты пользователей"
        ordering: ClassVar[list[str]] = ["-created_at"]
        indexes: ClassVar[list[models.Index]] = [
            models.Index(fields=["target_type", "target_id"], name="report_target_idx"),
        ]

    def __str__(self) -> str:
        return f"{self.get_target_type_display()}: {self.get_reason_display()}"
